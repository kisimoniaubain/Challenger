export function isSupportedLanguage(code) {
  return SUPPORTED_LANGUAGES.some((language) => language.code === code)
}

export function getLanguageLabel(code) {
  const language = SUPPORTED_LANGUAGES.find((entry) => entry.code === code)
  if (!language) {
    return 'English'
  }

  return `${language.name} (${language.nativeName})`
}

export function createTranslator(languageCode) {
  const currentCode = isSupportedLanguage(languageCode) ? languageCode : 'en'
  const dictionary = TRANSLATIONS[currentCode] || EN

  return function t(key) {
    return dictionary[key] || EN[key] || key
  }
}
